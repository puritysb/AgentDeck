import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = new URL('../', import.meta.url);
export function outputs() {
  const p = JSON.parse(readFileSync(new URL('shared/apme-retention-policy.json', root), 'utf8'));
  const header = '// Generated by scripts/generate-apme-retention.mjs; edit shared/apme-retention-policy.json.\n';
  return [
    ['bridge/src/apme/retention-policy.generated.ts', header + 'export const APME_RETENTION = ' + JSON.stringify(p, null, 2) + ' as const;\n'],
    ['apple/AgentDeck/Daemon/Apme/ApmeRetentionPolicy.generated.swift', header + '#if os(macOS)\nenum ApmeRetentionPolicy {\n' + Object.entries(p).map(([key, value]) => `    static let ${key} = ${typeof value === 'string' ? '#"' + value + '"#' : value}\n`).join('') + '}\n#endif\n'],
  ].map(([path, expected]) => ({ path: fileURLToPath(new URL(path, root)), expected }));
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const { path, expected } of outputs()) {
    if (process.argv.includes('--check')) {
      if (readFileSync(path, 'utf8') !== expected) throw new Error(`APME retention drift: ${path}`);
    } else writeFileSync(path, expected);
  }
}
