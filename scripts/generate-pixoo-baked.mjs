import { createRequire, builtinModules } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
const require = createRequire(new URL('../bridge/package.json', import.meta.url));
const { build } = require('esbuild');
const root = new URL('../', import.meta.url);
export async function outputs() {
  const result = await build({ entryPoints: [fileURLToPath(new URL('bridge/src/pixoo/pixoo-baked-entry.ts', root))],
    absWorkingDir: fileURLToPath(root), bundle: true, platform: 'browser', target: 'es2020', format: 'iife',
    minify: true, write: false, metafile: true, external: ['node:*', ...builtinModules],
    // Dot is painted outside this fixed profile by the explicitly gated host.
    // Do not bundle its optional rendering implementation into a Store resource.
    plugins: [{ name: 'fixed-pixoo-profile', setup(builder) {
      builder.onLoad({ filter: /[/\\]dot-pixels\.ts$/ }, () => ({ loader: 'ts', contents: 'export function paintDotPixels(rgb: Uint8Array): Uint8Array { return rgb; }' }));
    } }], alias: { '@agentdeck/shared/protocol': fileURLToPath(new URL('shared/src/protocol.ts', root)), '@agentdeck/shared': fileURLToPath(new URL('shared/src/index.ts', root)) } });
  if (Object.values(result.metafile.outputs).some(o => o.imports.length)) throw new Error('Pixoo bake must be self-contained');
  if (/\b(?:eval|Function|require|fetch|XMLHttpRequest)\s*\(/.test(result.outputFiles[0].text)) throw new Error('Pixoo core contains an execution or I/O primitive');
  const source = '// Generated fixed Pixoo pixel code; no I/O or host bridge.\n' + result.outputFiles[0].text;
  return [
    ['bridge/src/pixoo/pixoo-baked-source.generated.ts', '// Generated by scripts/generate-pixoo-baked.mjs.\nexport const PIXOO_BAKED_SOURCE = ' + JSON.stringify(source) + ';\n'],
    ['apple/AgentDeck/Resources/generated/pixoo-baked.generated.js', source],
  ].map(([path, expected]) => ({ path: fileURLToPath(new URL(path, root)), expected }));
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const { path, expected } of await outputs()) {
    if (process.argv.includes('--check')) {
      if (readFileSync(path, 'utf8') !== expected) throw new Error(`Pixoo baked source drift: ${path}`);
    } else writeFileSync(path, expected);
  }
}
