#!/usr/bin/env node
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
export const OUTPUT = 'apple/AgentDeck/Daemon/Server/GlancePolicy.generated.swift';
export function emitGlancePolicy() {
  const p = JSON.parse(fs.readFileSync('shared/glance-frame-policy.json', 'utf8'));
  const source = fs.readFileSync('bridge/src/glance-frame.ts', 'utf8');
  const iconSource = source.slice(source.indexOf('function iconSvg('), source.indexOf('// ===== SVG layout'))
    .replace('key: string', 'key').replace('): string', ')');
  const icon = Function(`${iconSource}; return iconSvg;`)();
  let hash = 0x811c9dc5;
  for (const name of p.fonts) for (const byte of fs.readFileSync(`bridge/assets/fonts/${name}`)) hash = Math.imul(hash ^ byte, 0x01000193) >>> 0;
  let policyHash = 0x811c9dc5;
  for (const byte of Buffer.from(JSON.stringify(p))) policyHash = Math.imul(policyHash ^ byte, 0x01000193) >>> 0;
  return '// GENERATED by scripts/generate-glance-policy.mjs. Do not edit.\n#if os(macOS)\nenum GlancePolicy {\n'
    + `    static let revision = ${JSON.stringify(p.revision)}\n    static let policySig = "${policyHash.toString(16).padStart(8, '0')}"\n    static let fontSig = "${hash.toString(16).padStart(8, '0')}"\n`
    + `    static let fonts: [String] = ${JSON.stringify(p.fonts)}\n`
    + `    static let bayer: [[UInt8]] = ${JSON.stringify(p.bayer)}\n`
    + ['sans','mono','gray'].map(key => `    static let ${key} = ${JSON.stringify(p[key])}\n`).join('')
    + '    static let boards: [String: GlanceFrame.Geometry] = [\n'
    + Object.entries(p.boards).map(([key,g])=>`        "${key}": .init(width: ${g.width}, height: ${g.height}, landscape: ${g.landscape}, rotate: ${!!g.rotateToPhysical}),\n`).join('')+'    ]\n'
    + ['GLANCE_MAX_WRAPUP_LINES','GLANCE_MAX_USAGE_ROWS','GLANCE_LINE_MAX_BYTES'].map(key => {
      const value = fs.readFileSync('shared/src/protocol.ts','utf8').match(new RegExp(`export const ${key} = (\\d+);`))[1];
      return `    static let ${key}: Int = ${value}\n`;
    }).join('')
    + '    static let aliases: [String: String] = [' + Object.entries(Function('return ' + fs.readFileSync('shared/src/esp32-boards.ts','utf8').match(/export const LEGACY_BOARD_IDS: Record<string, string> = (\{[\s\S]*?\});/)[1])()).map(([k,v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(', ') + ']\n'
    + '    enum Layout {\n'+Object.entries(p.layout).map(([key,v])=>`        static let ${key}: Double = ${v}\n`).join('')+'    }\n'
    + '    static func iconKey(_ code: Double) -> String {\n'
    + p.icons.map(rule => {
      const checks = [...(rule.eq ?? []).map(v => `code == ${v}`), ...(rule.ranges ?? []).map(([a,b])=>`(${a}...${b}).contains(code)`), ...(rule.lte !== undefined ? [`code <= ${rule.lte}`] : []), ...(rule.gte !== undefined ? [`code >= ${rule.gte}`] : [])];
      return `        if ${checks.join(' || ')} { return "${rule.key}" }\n`;
    }).join('') + '        return "cloud"\n    }\n'
    + '    static let icons: [String: String] = [\n'+['sun','partly','cloud','fog','rain','snow','storm'].map(k=>`        "${k}": ${JSON.stringify(icon(k))},\n`).join('')+'    ]\n}\n#endif\n';
}
export function emitTypeScriptPolicy() {
  return '// GENERATED from shared/glance-frame-policy.json. Do not edit.\nexport const GLANCE_POLICY = '
    + fs.readFileSync('shared/glance-frame-policy.json', 'utf8').trim() + ';\n';
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUTPUT, emitGlancePolicy());
  fs.writeFileSync('shared/src/glance-frame-policy.ts', emitTypeScriptPolicy());
}
