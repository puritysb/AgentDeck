import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = new URL('../', import.meta.url);
export function outputs() {
  const policy = JSON.parse(readFileSync(new URL('shared/antigravity-observation-policy.json', root), 'utf8'));
  const header = '// Generated by scripts/generate-antigravity-observation.mjs; edit shared/antigravity-observation-policy.json.\n';
  return [
    ['bridge/src/antigravity-policy.generated.ts', header + 'export const ANTIGRAVITY_POLICY = ' + JSON.stringify(policy, null, 2) + ' as const;\n'],
    ['apple/AgentDeck/Daemon/Session/AntigravityPolicy.generated.swift', header + '#if os(macOS)\nenum AntigravityPolicy {\n' + Object.entries(policy).map(([key, value]) => `    static let ${key} = ${typeof value === 'string' ? '#"' + value + '"#' : JSON.stringify(value)}\n`).join('') + '}\n#endif\n'],
  ].map(([path, expected]) => ({ path: fileURLToPath(new URL(path, root)), expected }));
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const { path, expected } of outputs()) {
    if (process.argv.includes('--check')) {
      if (readFileSync(path, 'utf8') !== expected) throw new Error(`Antigravity observation drift: ${path}`);
    } else writeFileSync(path, expected);
  }
}
