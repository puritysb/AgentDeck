import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = new URL('../', import.meta.url);
const targets = [
  ['apple/AgentDeck/UI/Monitor/ConnectionOverlay.swift', 'swift'],
  ['android/app/src/main/kotlin/dev/agentdeck/ui/common/ConnectionComponents.kt', 'kotlin'],
];
const marker = /    \/\/ BEGIN GENERATED NATIVE CONNECTION LABELS[\s\S]*?    \/\/ END GENERATED NATIVE CONNECTION LABELS/;

export function outputs() {
  const source = readFileSync(new URL('shared/src/connection-status.ts', root), 'utf8');
  const block = source.match(/export const NATIVE_CONNECTION_LABELS = \{([\s\S]*?)\} as const;/)?.[1];
  if (!block) throw new Error('Native connection labels missing');
  const labels = [...block.matchAll(/(\w+): '([^']+)'/g)].map(([, key, value]) => [key, value]);
  if (!labels.length) throw new Error('Native connection labels empty');
  return targets.map(([relative, language]) => {
    const path = fileURLToPath(new URL(relative, root));
    const current = readFileSync(path, 'utf8');
    if (!marker.test(current)) throw new Error(`Label markers missing: ${relative}`);
    const lines = labels.map(([key, value]) => language === 'swift'
      ? `    static let ${key} = ${JSON.stringify(value)}`
      : `    const val ${key.replace(/[A-Z]/g, c => '_' + c).toUpperCase()} = ${JSON.stringify(value)}`);
    const generated = ['    // BEGIN GENERATED NATIVE CONNECTION LABELS',
      '    // Generated by scripts/generate-connection-labels.mjs; edit shared/src/connection-status.ts.',
      ...lines, '    // END GENERATED NATIVE CONNECTION LABELS'].join('\n');
    return { path, current, expected: current.replace(marker, generated) };
  });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const { path, current, expected } of outputs()) {
    if (process.argv.includes('--check')) {
      if (current !== expected) throw new Error(`Connection label drift: ${path}`);
    } else if (current !== expected) writeFileSync(path, expected);
  }
}
