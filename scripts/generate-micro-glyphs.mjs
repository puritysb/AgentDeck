// Generate canonical dot-matrix masks directly from design/brand/*.svg.
// Outputs 24×24 standard masks, 9×9 Timebox Agent Beacon masks, and 8×8 TC001
// masks for TypeScript, Swift, and firmware consumers.
//
//   pnpm generate-micro-glyphs

import { writeFileSync, readFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import sharp from 'sharp';
import { rasterizeFeatureLayers, cppFeatureLayers, CPP_FEATURE_STRUCT } from './creature-feature-masks.mjs';
import { createHash } from 'node:crypto';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(__dirname, '../apple/AgentDeck/Daemon/Modules/MicroGlyphs.generated.swift');
const tsMaskOutFile = resolve(__dirname, '../bridge/src/pixoo/official-dot-glyphs.generated.ts');
const cppMaskOutFile = resolve(__dirname, '../esp32/src/ui/matrix/official_dot_glyphs_generated.h');

const OFFICIAL_GLYPHS = [
  ['claudeCode', 'claudecode'],
  ['codex', 'codex'],
  ['openCode', 'opencode'],
  ['openClaw', 'openclaw'],
  ['antigravity', 'antigravity'],
  ['kiro', 'kiro'],
  ['hermes', 'hermes'],
  ['zai', 'zai'],
];
const STANDARD_MASK_SIZE = 24;
const TIMEBOX_MASK_SIZE = 9;
const TC001_MASK_SIZE = 8;

async function rasterizeOfficialGlyph(fileStem, size, fit = 'fill') {
  const svg = readFileSync(resolve(__dirname, `../design/brand/${fileStem}.svg`), 'utf8')
    .replaceAll('currentColor', '#ffffff');
  const { data, info } = await sharp(Buffer.from(svg), { density: 384 })
    .resize(size, size, { fit, background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const alpha = [];
  for (let i = 0; i < size * size; i++) alpha.push(data[i * info.channels + info.channels - 1]);
  return alpha;
}

const officialMasks = {};
for (const [key, fileStem] of OFFICIAL_GLYPHS) {
  officialMasks[key] = {
    standard: await rasterizeOfficialGlyph(fileStem, STANDARD_MASK_SIZE),
    timebox: await rasterizeOfficialGlyph(fileStem, TIMEBOX_MASK_SIZE),
    tc001: await rasterizeOfficialGlyph(fileStem, TC001_MASK_SIZE),
    standardFeatures: await rasterizeFeatureLayers(fileStem, STANDARD_MASK_SIZE),
    timeboxFeatures: await rasterizeFeatureLayers(fileStem, TIMEBOX_MASK_SIZE),
    tc001Features: await rasterizeFeatureLayers(fileStem, TC001_MASK_SIZE),
  };
}

// GitHub is a CI provider/helper, never a session agent. Preserve the official
// SVG and its 98:96 aspect ratio; only sample its coverage for compact devices.
const githubSvg = readFileSync(resolve(__dirname, '../design/brand/github.svg'));
const githubAlpha = await rasterizeOfficialGlyph('github', TC001_MASK_SIZE, 'contain');
const githubStandard = await rasterizeOfficialGlyph('github', STANDARD_MASK_SIZE, 'contain');
const githubRows = Array.from({ length: TC001_MASK_SIZE }, (_, y) => {
  let row = 0;
  for (let x = 0; x < TC001_MASK_SIZE; x++) {
    if (githubAlpha[y * TC001_MASK_SIZE + x] >= 128) row |= 0x80 >> x;
  }
  return row;
});
writeFileSync(
  resolve(__dirname, '../shared/src/ci-github-glyph.generated.ts'),
  `// AUTO-GENERATED by scripts/generate-micro-glyphs.mjs — DO NOT EDIT.\n` +
    `// Canonical source: design/brand/github.svg (official GitHub Invertocat).\n` +
    `// 8x8 alpha coverage >=128; MSB is the left pixel. Aspect ratio preserved.\n` +
    `export const CI_GITHUB_GLYPH_SOURCE_SHA256 = '${createHash('sha256').update(githubSvg).digest('hex')}';\n` +
    `export const CI_GITHUB_GLYPH_SIZE = ${TC001_MASK_SIZE};\n` +
    `export const CI_GITHUB_GLYPH = [${githubRows.join(', ')}] as const;\n` +
    `export const CI_GITHUB_ALPHA_SIZE = ${STANDARD_MASK_SIZE};\n` +
    `export const CI_GITHUB_ALPHA = [${githubStandard.join(', ')}] as const;\n`,
);

function wrapNumbers(values, indent, perLine = 24) {
  const lines = [];
  for (let i = 0; i < values.length; i += perLine) {
    lines.push(`${indent}${values.slice(i, i + perLine).join(', ')},`);
  }
  return lines.join('\n');
}

const tsMasks = OFFICIAL_GLYPHS.map(([key]) => `  ${key}: new Uint8Array([\n${wrapNumbers(officialMasks[key].standard, '    ')}\n  ]),`).join('\n');
const tsTimeboxMasks = OFFICIAL_GLYPHS.map(([key]) => `  ${key}: new Uint8Array([\n${wrapNumbers(officialMasks[key].timebox, '    ', 9)}\n  ]),`).join('\n');
const tsTc001Masks = OFFICIAL_GLYPHS.map(([key]) => `  ${key}: new Uint8Array([\n${wrapNumbers(officialMasks[key].tc001, '    ', 8)}\n  ]),`).join('\n');
const tsGlyphUnion = OFFICIAL_GLYPHS.map(([key]) => `'${key}'`).join(' | ');
const tsMaskSource = `// AUTO-GENERATED by scripts/generate-micro-glyphs.mjs — DO NOT EDIT.\n// Canonical source: design/brand/*.svg. Regenerate with: pnpm generate-micro-glyphs\n\nexport type OfficialDotGlyphName = ${tsGlyphUnion};\nexport const OFFICIAL_DOT_GLYPH_SIZE = ${STANDARD_MASK_SIZE};\nexport const OFFICIAL_DOT_GLYPHS: Record<OfficialDotGlyphName, Uint8Array> = {\n${tsMasks}\n};\n\nexport const OFFICIAL_TIMEBOX_GLYPH_SIZE = ${TIMEBOX_MASK_SIZE};\nexport const OFFICIAL_TIMEBOX_GLYPHS: Record<OfficialDotGlyphName, Uint8Array> = {\n${tsTimeboxMasks}\n};\n\nexport const OFFICIAL_TC001_GLYPH_SIZE = ${TC001_MASK_SIZE};\nexport const OFFICIAL_TC001_GLYPHS: Record<OfficialDotGlyphName, Uint8Array> = {\n${tsTc001Masks}\n};\n`;
const tsFeatures = ['standard', 'timebox', 'tc001'].map(kind => `export const OFFICIAL_${kind.toUpperCase()}_FEATURES = ${JSON.stringify(Object.fromEntries(OFFICIAL_GLYPHS.map(([key]) => [key, officialMasks[key][kind + 'Features']])), null, 2)} as const;`).join('\n');
writeFileSync(tsMaskOutFile, tsMaskSource + '\n' + tsFeatures + '\n');

const swiftMasks = OFFICIAL_GLYPHS.map(([key]) => `        .${key}: [\n${wrapNumbers(officialMasks[key].standard, '            ')}\n        ],`).join('\n');
const swiftTimeboxMasks = OFFICIAL_GLYPHS.map(([key]) => `        .${key}: [\n${wrapNumbers(officialMasks[key].timebox, '            ', 9)}\n        ],`).join('\n');
const swiftTc001Masks = OFFICIAL_GLYPHS.map(([key]) => `        .${key}: [\n${wrapNumbers(officialMasks[key].tc001, '            ', 8)}\n        ],`).join('\n');

function cppRows(key, values) {
  const upper = key.replace(/([A-Z])/g, '_$1').toUpperCase();
  return `static const uint8_t ${upper}[SIZE * SIZE] = {\n${wrapNumbers(values, '    ', 8)}\n};`;
}
const cppMasks = OFFICIAL_GLYPHS.map(([key]) => cppRows(key, officialMasks[key].tc001) + '\n' + cppFeatureLayers(key.replace(/([A-Z])/g, '_$1').toUpperCase(), officialMasks[key].tc001Features)).join('\n\n');
const cppMaskSource = `// AUTO-GENERATED by scripts/generate-micro-glyphs.mjs — DO NOT EDIT.\n// Canonical source: design/brand/*.svg. Regenerate with: pnpm generate-micro-glyphs\n#pragma once\n#include <cstdint>\n\nnamespace OfficialDotGlyphs {\nconstexpr int SIZE = ${TC001_MASK_SIZE};\n\n${CPP_FEATURE_STRUCT}\n\n${cppMasks}\n\n}  // namespace OfficialDotGlyphs\n`;
writeFileSync(cppMaskOutFile, cppMaskSource);

// No platform guard: the masks feed both the macOS daemon renderers (Pixoo/
// Timebox/TC001) AND the cross-platform Device Preview surfaces — the iOS
// build broke when this file was #if os(macOS) while UI/Preview referenced
// OfficialTc001Glyphs.
const header = `// MicroGlyphs.generated.swift — AUTO-GENERATED, DO NOT EDIT.
//
// Source of truth: design/brand/*.svg
// Regenerate with: pnpm generate-micro-glyphs

import Foundation

enum OfficialDotGlyph: Hashable {
    case ${OFFICIAL_GLYPHS.map(([key]) => key).join(', ')}
}

enum OfficialDotGlyphs {
    static let size = ${STANDARD_MASK_SIZE}
    static let masks: [OfficialDotGlyph: [UInt8]] = [
${swiftMasks}
    ]
}

enum OfficialTimeboxGlyphs {
    static let size = ${TIMEBOX_MASK_SIZE}
    static let masks: [OfficialDotGlyph: [UInt8]] = [
${swiftTimeboxMasks}
    ]
}

enum OfficialTc001Glyphs {
    static let size = ${TC001_MASK_SIZE}
    static let masks: [OfficialDotGlyph: [UInt8]] = [
${swiftTc001Masks}
    ]
}
`;

const swiftFeatures = ['standard', 'timebox', 'tc001'].map(kind => `enum Official${kind[0].toUpperCase() + kind.slice(1)}Features {\n    static let layers: [OfficialDotGlyph: [OfficialFeatureLayer]] = [\n${OFFICIAL_GLYPHS.map(([key]) => '        .' + key + ': [' + officialMasks[key][kind + 'Features'].map(f => `OfficialFeatureLayer(x: ${f.x}, y: ${f.y}, width: ${f.width}, height: ${f.height}, alpha: [${f.alpha.join(', ')}], red: ${f.rgb[0]}, green: ${f.rgb[1]}, blue: ${f.rgb[2]}, monochromeInk: ${f.monochrome === 'ink'}, creatureMonochromeInk: ${f.monochromeCreature === 'ink'})`).join(', ') + '],').join('\n')}\n    ]\n}`).join('\n\n');
writeFileSync(outFile, header + '\nstruct OfficialFeatureLayer {\n    let x, y, width, height: Int\n    let alpha: [UInt8]\n    let red, green, blue: UInt8\n    let monochromeInk: Bool\n    let creatureMonochromeInk: Bool\n}\n\n' + swiftFeatures + '\n');
console.log(`generate-micro-glyphs: wrote ${OFFICIAL_GLYPHS.length} canonical dot-matrix masks at 24/9/8px`);
