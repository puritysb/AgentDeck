import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = new URL('../', import.meta.url);
export function outputs() {
  const p = JSON.parse(readFileSync(new URL('shared/transport-auth-policy.json', root), 'utf8'));
  const header = '// Generated by scripts/generate-transport-auth-policy.mjs; edit shared/transport-auth-policy.json.\n';
  return [
    ['bridge/src/transport-auth-policy.generated.ts', header + 'export const TRANSPORT_AUTH_POLICY = ' + JSON.stringify(p) + ' as const;\n'],
    ['esp32/src/net/transport_auth_policy.generated.h', header + '#pragma once\n#include <cstdint>\nnamespace TransportAuthPolicy {\n' + Object.entries(p).map(([k,v]) => `static constexpr uint16_t ${k} = ${v};\n`).join('') + '}\n'],
  ].map(([path, expected]) => ({path: fileURLToPath(new URL(path, root)), expected}));
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const {path, expected} of outputs()) {
    if (process.argv.includes('--check')) { if (readFileSync(path, 'utf8') !== expected) throw new Error('Transport auth policy drift: ' + path); }
    else writeFileSync(path, expected);
  }
}
