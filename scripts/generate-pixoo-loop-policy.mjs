import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = new URL('../', import.meta.url);
export function outputs() {
  const policy = JSON.parse(readFileSync(new URL('shared/pixoo-loop-policy.json', root), 'utf8'));
  policy.gammaLUT = Array.from({ length: 256 }, (_, i) => Math.round(Math.pow(i / 255, policy.gammaExponent) * 255));
  const header = '// Generated by scripts/generate-pixoo-loop-policy.mjs; edit shared/pixoo-loop-policy.json.\n';
  return [
    ['bridge/src/pixoo/pixoo-loop-policy.generated.ts', header + 'export const PIXOO_LOOP_POLICY = ' + JSON.stringify(policy, null, 2) + ' as const;\n'],
    ['apple/AgentDeck/Daemon/Modules/PixooLoopPolicy.generated.swift', header + '#if os(macOS)\nenum PixooLoopPolicy {\n' + Object.entries(policy).map(([key, value]) => `    static let ${key} = ${JSON.stringify(value)}\n`).join('') + '}\n#endif\n'],
  ].map(([path, expected]) => ({ path: fileURLToPath(new URL(path, root)), expected }));
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const { path, expected } of outputs()) {
    if (process.argv.includes('--check')) {
      if (readFileSync(path, 'utf8') !== expected) throw new Error(`Pixoo loop policy drift: ${path}`);
    } else writeFileSync(path, expected);
  }
}
