import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = new URL('../', import.meta.url);
export function outputs() {
  const policy = JSON.parse(readFileSync(new URL('shared/calendar-policy.json', root), 'utf8'));
  const windowsZones = JSON.parse(readFileSync(new URL('shared/calendar-windows-zones.json', root), 'utf8'));
  policy.windowsZones = windowsZones.zones;
  const protocol = readFileSync(new URL('shared/src/protocol.ts', root), 'utf8');
  for (const [key, name] of [['wireMaxEvents', 'GLANCE_MAX_EVENTS'], ['titleBytes', 'GLANCE_EVENT_TITLE_MAX_BYTES']]) {
    const value = protocol.match(new RegExp('export const ' + name + ' = (\\d+);'))?.[1];
    if (!value) throw new Error('Missing calendar wire limit ' + name);
    policy[key] = Number(value);
  }
  const license = readFileSync(new URL('shared/calendar-windows-zones-LICENSE.txt', root), 'utf8');
  const header = '/* Windows time zones: Unicode CLDR release-48, territory 001.\n' + license + '*/\n' + '// Generated by scripts/generate-calendar-policy.mjs; edit shared/calendar-policy.json.\n';
  return [
    ['apple/AgentDeck/Resources/Calendar-ThirdPartyNotices.txt', 'Windows timezone mapping: Unicode CLDR release-48, territory 001.\n\n' + license],
    ['bridge/src/calendar-policy.generated.ts', header + 'export const CALENDAR_POLICY = ' + JSON.stringify(policy, null, 2) + ' as const;\n'],
    ['apple/AgentDeck/Daemon/Server/CalendarPolicy.generated.swift', header + '#if os(macOS)\nenum CalendarPolicy {\n' + Object.entries(policy).map(([key, value]) => `    static let ${key} = ${typeof value === 'string' ? '#"' + value + '"#' : !Array.isArray(value) && value && typeof value === 'object' ? '[' + Object.entries(value).map(([k, v]) => JSON.stringify(k) + ': ' + JSON.stringify(v)).join(', ') + ']' : JSON.stringify(value)}\n`).join('') + '}\n#endif\n'],
  ].map(([path, expected]) => ({ path: fileURLToPath(new URL(path, root)), expected }));
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const { path, expected } of outputs()) {
    if (process.argv.includes('--check')) {
      if (readFileSync(path, 'utf8') !== expected) throw new Error(`Calendar policy drift: ${path}`);
    } else writeFileSync(path, expected);
  }
}
