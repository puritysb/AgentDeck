#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
/** The body of a one-line numeric predicate, lifted from the TS source. */
const predicateOf = (source) => source.match(/return ([^;]+);/)[1];

export function emitCpp(policy, lunaSource, separators = ' ·:-', creditsSource, units) {
  // The numeric predicates are emitted from the actual TS function bodies.
  const predicate = predicateOf(lunaSource);
  return `// GENERATED by scripts/generate-usage-presentation.mjs. DO NOT EDIT.
// SSOT: shared/src/usage-presentation.ts
#pragma once
#include <cmath>
#include <cstdio>
#include <cstring>
#include <cctype>
namespace UsagePresentation {
static constexpr const char* Heading = "${policy.heading}";
static constexpr const char* Providers[] = {${policy.providers.map(p => JSON.stringify(p.label)).join(',')}};
inline bool lunaActive(float primary, float secondary, float reserve) { return ${predicate}; }
// usageCreditsActive: balance is -1 when unknown, +INFINITY when unlimited.
inline bool creditsActive(float primary, float secondary, double balance) { return ${predicateOf(creditsSource)}; }
// formatCreditBalance: truncated, integer-only, "∞" (UTF-8) when unlimited.
inline void formatCreditBalance(double balance, char* out, size_t outLen) {
    if (!out || outLen == 0) return;
    if (std::isinf(balance) && balance > 0) { std::snprintf(out, outLen, "\\xE2\\x88\\x9E"); return; }
    if (!(balance > 0)) { std::snprintf(out, outLen, "0"); return; }
    struct Unit { double divisor; const char* suffix; };
    static constexpr Unit units[] = {${units.map(u => `{${u.divisor}, ${JSON.stringify(u.suffix)}}`).join(', ')}};
    for (const Unit& u : units) {
        if (balance < u.divisor) continue;
        const long long tenths = static_cast<long long>(std::floor(balance * 10 / u.divisor));
        if (tenths >= 1000 || tenths % 10 == 0) std::snprintf(out, outLen, "%lld%s", tenths / 10, u.suffix);
        else std::snprintf(out, outLen, "%lld.%lld%s", tenths / 10, tenths % 10, u.suffix);
        return;
    }
    if (balance >= 10) { std::snprintf(out, outLen, "%lld", static_cast<long long>(std::floor(balance))); return; }
    const long long tenths = static_cast<long long>(std::floor(balance * 10));
    if (tenths % 10 == 0) std::snprintf(out, outLen, "%lld", tenths / 10);
    else std::snprintf(out, outLen, "%lld.%lld", tenths / 10, tenths % 10);
}
inline bool startsWith(const char* name, const char* prefix) {
    while (*name == ' ') ++name;
    while (*prefix) { if (std::tolower(static_cast<unsigned char>(*name++)) != std::tolower(static_cast<unsigned char>(*prefix++))) return false; }
    return true;
}
inline int subscriptionProvider(const char* name) {
${policy.providers.map((p,i) => `    if (${p.prefixes.map(v=>`startsWith(name, ${JSON.stringify(v)})`).join(' || ')}) return ${i};`).join('\n')}
    return -1;
}
// usageSubscriptionTier: the subscription name without its provider prefix.
inline void subscriptionTier(const char* name, char* out, size_t outLen) {
    if (!out || outLen == 0) return;
    out[0] = '\\0';
    if (!name) return;
    while (*name == ' ') ++name;
    static constexpr const char* prefixes[] = {${policy.providers.flatMap(p => p.prefixes).map(v => JSON.stringify(v)).join(',')}};
    const char* tail = nullptr;
    for (const char* prefix : prefixes) if (startsWith(name, prefix)) { tail = name + std::strlen(prefix); break; }
    if (tail) {
        // Separators: ${JSON.stringify(separators)} (UTF-8 middle dot is two bytes).
        for (;;) {
            if (*tail && std::strchr(${JSON.stringify(separators.replace('·', ''))}, *tail)) { ++tail; continue; }
            if (static_cast<unsigned char>(tail[0]) == 0xC2 && static_cast<unsigned char>(tail[1]) == 0xB7) { tail += 2; continue; }
            break;
        }
    }
    // A prefix-only name ("Claude") has no tier: leave it empty.
    const char* src = tail ? tail : name;
    size_t n = std::strlen(src);
    while (n && src[n - 1] == ' ') --n;
    if (n >= outLen) n = outLen - 1;
    std::memcpy(out, src, n);
    out[n] = '\\0';
}
}
`;
}
export function emitSwift(policy, lunaSource, separators = ' ·:-', creditsSource, units) {
  const predicate = predicateOf(lunaSource);
  return `// GENERATED from shared/src/usage-presentation.ts. DO NOT EDIT.
import Foundation

enum UsagePresentation {
    static let heading = "${policy.heading}"
    static func lunaActive(_ primary: Double, _ secondary: Double, _ reserve: Double) -> Bool { return ${predicate} }
    /// usageCreditsActive: balance is -1 when unknown, +infinity when unlimited.
    static func creditsActive(_ primary: Double, _ secondary: Double, _ balance: Double) -> Bool { return ${predicateOf(creditsSource)} }
    /// formatCreditBalance: truncated, integer-only, "∞" when unlimited.
    static func formatCreditBalance(_ balance: Double) -> String {
        if balance == .infinity { return "\\u{221E}" }
        if !balance.isFinite || balance <= 0 { return "0" }
        for (divisor, suffix) in [${units.map(u => `(${u.divisor}.0, ${JSON.stringify(u.suffix)})`).join(', ')}] where balance >= divisor {
            let tenths = Int((balance * 10 / divisor).rounded(.down))
            return tenths >= 1000 || tenths % 10 == 0 ? "\\(tenths / 10)\\(suffix)" : "\\(tenths / 10).\\(tenths % 10)\\(suffix)"
        }
        if balance >= 10 { return "\\(Int(balance.rounded(.down)))" }
        let tenths = Int((balance * 10).rounded(.down))
        return tenths % 10 == 0 ? "\\(tenths / 10)" : "\\(tenths / 10).\\(tenths % 10)"
    }
    /// usageSubscriptionTier: the subscription name without its provider prefix.
    static func subscriptionTier(_ name: String) -> String {
        let trimmed = name.trimmingCharacters(in: .whitespaces)
        for prefix in [${policy.providers.flatMap(p => p.prefixes).map(v => JSON.stringify(v)).join(', ')}]
            where trimmed.lowercased().hasPrefix(prefix.lowercased()) {
            let tail = trimmed.dropFirst(prefix.count).drop { ${JSON.stringify(separators)}.contains($0) }
            let tier = tail.trimmingCharacters(in: .whitespaces)
            return tier
        }
        return trimmed
    }
}
`;
}
export function emitKotlin(policy, lunaSource, _separators, creditsSource, units) {
  const predicate = predicateOf(lunaSource);
  return `// GENERATED from shared/src/usage-presentation.ts. DO NOT EDIT.
package dev.agentdeck.util
object UsagePresentation {
    const val heading = "${policy.heading}"
    fun lunaActive(primary: Double, secondary: Double, reserve: Double): Boolean = ${predicate}
    /** usageCreditsActive: balance is -1 when unknown, +Infinity when unlimited. */
    fun creditsActive(primary: Double, secondary: Double, balance: Double): Boolean = ${predicateOf(creditsSource)}
    /** formatCreditBalance: truncated, integer-only, "∞" when unlimited. */
    fun formatCreditBalance(balance: Double): String {
        if (balance == Double.POSITIVE_INFINITY) return "\\u221E"
        if (!balance.isFinite() || balance <= 0) return "0"
        for ((divisor, suffix) in listOf(${units.map(u => `${u.divisor}.0 to ${JSON.stringify(u.suffix)}`).join(', ')})) {
            if (balance < divisor) continue
            val tenths = kotlin.math.floor(balance * 10 / divisor).toLong()
            return if (tenths >= 1000 || tenths % 10 == 0L) "\${tenths / 10}\$suffix" else "\${tenths / 10}.\${tenths % 10}\$suffix"
        }
        if (balance >= 10) return kotlin.math.floor(balance).toLong().toString()
        val tenths = kotlin.math.floor(balance * 10).toLong()
        return if (tenths % 10 == 0L) "\${tenths / 10}" else "\${tenths / 10}.\${tenths % 10}"
    }
}
`;
}
export const target = 'esp32/src/util/usage_presentation.generated.h';
export const outputs = [[target,emitCpp],['apple/AgentDeck/Model/UsagePresentation.generated.swift',emitSwift],['android/app/src/main/kotlin/dev/agentdeck/util/UsagePresentation.kt',emitKotlin]];
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { USAGE_PRESENTATION, usageLunaActive, USAGE_TIER_SEPARATORS, usageCreditsActive, CREDIT_BALANCE_UNITS } = await import('../shared/dist/usage-presentation.js');
  for (const [target,emit] of outputs) {
    const output = emit(USAGE_PRESENTATION, usageLunaActive.toString(), USAGE_TIER_SEPARATORS, usageCreditsActive.toString(), CREDIT_BALANCE_UNITS);
    if (process.argv.includes('--check')) {
      if (fs.readFileSync(path.join(root,target),'utf8') !== output) throw Error('Usage presentation mirror drift');
    } else fs.writeFileSync(path.join(root,target),output);
  }
}
