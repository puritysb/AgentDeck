"""Encode the generated ocean as a zlib-compressed LVGL RGB565 image.
Python 3 + Pillow. --check verifies the committed consumer against the PNG.
The firmware inflates it once into PSRAM (ips10_workspace.cpp, oceanImage()).
"""
from pathlib import Path
import hashlib
import sys
import zlib
from PIL import Image

source = Path(__file__).with_name('ocean.png')
target = source.parents[2] / 'esp32/src/ui/widgets/ips10_ocean_generated.h'
image = Image.open(source).convert('RGBA').resize((640,400), Image.Resampling.LANCZOS)
assert image.size == (640, 400)
color, alpha = bytearray(), bytearray()
pixels = image.tobytes()
for i in range(0, len(pixels), 4):
    r, g, b, a = pixels[i:i+4]
    value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    color.extend((value & 255, value >> 8))
    alpha.append(a)
data = bytes(color)
packed = zlib.compress(data, 9)
assert zlib.decompress(packed) == data
lines = ['#pragma once', '// Generated by design/ips10/encode_ocean.py. Do not edit.',
         '// Generated underwater background; input PNG SHA256:',
         '// ' + hashlib.sha256(source.read_bytes()).hexdigest(),
         '#include <stddef.h>', '#include <stdint.h>', 'namespace IPS10Ocean {',
         '// 640x400 RGB565 (stride 1280) as one zlib stream. Raw it is 500 KiB, about',
         '// 8% of the 6 MB OTA slot; the firmware inflates it once into PSRAM.',
         'static constexpr int Width = 640, Height = 400, Stride = 1280;',
         f'static constexpr size_t RawBytes = {len(data)};',
         'alignas(4) static const uint8_t compressed[] = {']
lines += ['    ' + ','.join(f'0x{b:02x}' for b in packed[i:i+24]) + ',' for i in range(0, len(packed), 24)]
lines += ['};', '}', '']
result = '\n'.join(lines)
if '--check' in sys.argv:
    assert target.read_text() == result, 'Ocean consumer drift: run design/ips10/encode_ocean.py'
    print('IPS10 ocean: PNG and LVGL consumer match')
else:
    target.write_text(result)
