"""Generate Mini Dock icons and palette from AgentDeck's canonical assets."""

from pathlib import Path
import re
import struct
import zlib

ROOT = Path(__file__).resolve().parents[2]
APP = Path(__file__).resolve().parent / "AgentDeck"
MASKS = (ROOT / "esp32/src/ui/terrarium/creature_glyphs_generated.h").read_text()
TOKENS = (ROOT / "design/tokens.css").read_text()
USAGE_RULES = (ROOT / "shared/src/usage-presentation.ts").read_text()
SEVERITY = (ROOT / "shared/src/usage-severity.ts").read_text()
FRESHNESS = (ROOT / "shared/src/format-utils.ts").read_text()
CREATURES = {
    "claude-code": ("OCTOPUS", "brand-claude-code"),
    "codex": ("CODEX", "brand-codex"),
    "openclaw": ("OPENCLAW_MARK", "brand-openclaw"),
    "opencode": ("OPENCODE", "brand-opencode-on-dark"),
    "antigravity": ("ANTIGRAVITY", "brand-antigravity"),
    "kiro": ("KIRO", "brand-kiro"),
    "hermes": ("HERMES", "brand-hermes-on-dark"),
    "zai": ("ZAI", "brand-zai"),
}


def rgb(name):
    return tuple(bytes.fromhex(re.search(r"--" + name + r":\s*#([a-fA-F0-9]{6})", TOKENS)[1]))


def array(name):
    match = re.search(r"\b" + name + r"\[[^\]]+\] = \{([^}]+)\}", MASKS)
    return [int(n) for n in re.findall(r"\d+", match[1])]


def chunk(kind, data):
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))


def creature_png(mask, color):
    pixels = [(*color, a) for a in array(mask + "_A8")]
    layers = re.search(mask + r"_FEATURES\[\d+\] = \{(.*?)\n\};", MASKS, re.S)[1]
    for fields in re.findall(r"\{([^}]+)\}", layers):
        x, y, width, height, alpha, red, green, blue, *_ = fields.split(", ")
        x, y, width, height = map(int, (x, y, width, height))
        if alpha == "nullptr":
            continue
        feature = array(alpha)
        ink = tuple(map(int, (red, green, blue)))
        for row in range(height):
            for col in range(width):
                i = (y + row) * 64 + x + col
                over = feature[row * width + col]
                under = pixels[i][3] * (255 - over) // 255
                total = over + under
                if total:
                    pixels[i] = (*( (ink[c] * over + pixels[i][c] * under) // total
                                    for c in range(3)), total)
    # Sample the canonical mask into the 48 px Mini Dock tile.
    size = 48
    raw = b"".join(b"\0" + bytes(channel for x in range(size)
                                  for channel in pixels[(y * 64 // size) * 64 + x * 64 // size])
                   for y in range(size))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


resources = APP / "resources"
resources.mkdir(exist_ok=True)
for agent, (mask, color) in CREATURES.items():
    (resources / (agent + ".png")).write_bytes(creature_png(mask, rgb(color)))

palette = {
    "ATTENTION_RGB": rgb("ui-attn"),
    "WORKING_RGB": rgb("ui-cyan"),
    "IDLE_RGB": rgb("ui-idle-dark"),
    "BACKGROUND_RGB": rgb("ui-water-deep"),
    "PANEL_RGB": rgb("ui-water-mid"),
    "BORDER_RGB": rgb("ui-water-shallow"),
    "TEXT_RGB": rgb("ui-hud-text"),
    "SUBTEXT_RGB": rgb("ui-hud-subtext"),
    "HEALTH_RGB": rgb("ui-ok"),
    "ERROR_RGB": rgb("ui-error"),
    "WARNING_PERCENT": int(re.search(r"warning: (\d+)", SEVERITY)[1]),
    "CRITICAL_PERCENT": int(re.search(r"critical: (\d+)", SEVERITY)[1]),
    "CODEX_AGED_SECONDS": int(re.search(r"CODEX_SNAPSHOT_STALE_MS = (\d+) \* 60_000", FRESHNESS)[1]) * 60,
    "CREDIT_UNITS": tuple((int(number.replace("_", "")), suffix)
                          for number, suffix in re.findall(r"divisor: ([0-9_]+), suffix: '([A-Z])'", USAGE_RULES)),
    "PULSE_MS": int(re.search(r"--d-pulse:\s*(\d+)ms", TOKENS)[1]),
    "CREATURES": tuple(CREATURES),
}
(APP / "palette.py").write_text(
    "# Generated by generate_assets.py from AgentDeck design tokens and creature masks.\n"
    + "".join(f"{key} = {value!r}\n" for key, value in palette.items())
)
